package com.phian404.survivalpoints.init;

/**
 * Единый центр настройки поведения стража.
 *
 * <p>Раньше пороги были разбросаны по коду голдов (3.0 / 7.0 / 20 / 32 / 64 / 16 блоков,
 * 0.3 / 0.4 / 0.7 от максимального ХП), из-за чего их невозможно было согласовать
 * между собой. Теперь все значения живут здесь и используются только отсюда.
 */
public final class GuardianTuning {

    private GuardianTuning() {
    }

    // ==================== Пороги здоровья (доля от максимума) ====================

    /** Ниже этой доли ХП страж впадает в панику: всегда арбалет, отход, зов союзников. */
    public static final float PANIC_HP_RATIO = 0.30F;

    /** Ниже этой доли ХП (и если нет цели) страж ест хлеб для регенерации. */
    public static final float EAT_BREAD_HP_RATIO = 0.70F;

    /**
     * Высота глаз стража. Ровно как у игрока (1.62) — иначе страж наклоняет
     * голову вниз, глядя на игрока, потому что его глаза выше.
     */
    public static final float EYE_HEIGHT = 1.62F;

    /** Максимальный наклон головы (в градусах) при взгляде на цель. */
    public static final float MAX_HEAD_PITCH = 35.0F;

    // ==================== Разворот тела ====================

    /**
     * Максимальная скорость доворота тела к цели (градусов за тик).
     *
     * <p>14 градусов за тик — это 280°/с: страж резко доворачивает корпус к
     * врагу, как живой моб в атаке, а не медленно ползёт, как сервопривод.
     * Разворот на 180° занимает около 14 тиков (0.7 с).
     */
    public static final float FACE_TURN_SPEED_DEG = 24.0F;

    /**
     * Максимальная скорость доворота головы к цели (градусов за тик).
     *
     * <p>Голова доворачивается быстрее корпуса — как у живого моба, который
     * поворачивает голову, не разворачивая всего тела.
     */
    public static final float FACE_HEAD_SPEED_DEG = 30.0F;

    /**
     * На сколько градусов голова может отклониться от корпуса.
     *
     * <p>Как в ванили: {@code LookControl.clampHeadRotationToBody()} не даёт
     * голове отойти от корпуса дальше, чем на 75° (максимум моба).
     */
    public static final float MAX_HEAD_YAW_OFFSET = 75.0F;

    /**
     * Доля от расхождения, которую корпус доворачивает за тик.
     *
     * <p>Так же, как у ванильных мобов: тело подтягивается к нужному курсу
     * плавно и с замедлением, а не прыгает на всю величину. Вместе с
     * пределом скорости даёт быстрый, но ровный доворот.
     */
    public static final float FACE_SMOOTHING = 0.5F;

    /**
     * Скорость изменения наклона головы (доля за тик).
     *
     * <p>Наклон двигается медленнее поворота: голова доворачивается по вертикали
     * плавно, без рывков.
     */
    public static final float FACE_PITCH_SPEED = 0.2F;

    /**
     * Допуск, в котором корпус считается направленным на цель.
     *
     * <p>Пока тело не доворачивается настолько, страж не стреляет: иначе
     * выстрел уходит боком. Если развернуться невозможно, стрельбы нет вовсе
     * — безопаснее, чем выстрел в произвольную сторону.
     */
    public static final float FIRE_AIM_TOLERANCE_DEG = 12.0F;

    /**
     * Порог, ниже которого доворот считается завершённым и угол «защёлкивается».
     *
     * <p>Нужен, чтобы не отправлять пакет поворота каждый тик: при плавном
     * довороте угол никогда не сравнивается с целью точно, и значение
     * продолжало бы «дрожать» на доли градуса.
     */
    public static final float FACE_SNAP_ANGLE = 1.5F;

    /**
     * Задержка перед выстрелом (тики) — «взвод» после полного заряда.
     *
     * <p>Без неё страж выпускает стрелу ровно в тот тик, когда арбалет
     * дозарядился, и выглядит это так, будто он схватил арбалет и тут же
     * выстрелил. Пауза в полсекунды, пока страж держит оружие на цели,
     * выглядит естественнее.
     */
    public static final int PRE_SHOT_DELAY_TICKS = 10;

    /** На сколько блоков вперёд от глаз появляется стрела (из руки, а не из головы). */
    public static final double ARROW_SPAWN_OFFSET = 0.6D;

    /**
     * Скорость стрелы. Влияет и на урон: в 1.20.1 урон стрелы равен
     * ceil(длина вектора скорости × baseDamage).
     */
    public static final double ARROW_SPEED = 2.2D;

    /** Множитель урона стрелы. Итог: ceil(2.2 × 2.5) = 6 урона. */
    public static final double ARROW_DAMAGE_MULTIPLIER = 2.5D;

    /** Гравитация стрелы (блоков за тик в квадрате) — нужна для компенсации падения. */
    public static final double ARROW_GRAVITY = 0.05D;

    /**
     * Дополнительный сдвиг точки появления стрелы вперёд по направлению выстрела.
     *
     * <p>Сложен с {@link #ARROW_SPAWN_OFFSET}: стрела появляется не внутри
     * модели стража, а перед ней, и сразу двигается свободно. Направление,
     * скорость, урон и траектория после появления при этом не меняются —
     * меняется только точка старта.
     */
    public static final double ARROW_SPAWN_FORWARD = 0.35D;

    /** Сдвиг точки появления стрелы вниз — чтобы она не возникала внутри модели. */
    public static final double ARROW_SPAWN_DOWN = 0.18D;

    /**
     * Коэффициент упреждения при прицеливании.
     *
     * <p>1.0 — целиться ровно туда, куда цель окажется в момент попадания стрелы.
     * Меньше 1.0 — недобор (цель не догонит), больше 1.0 — перелёт.
     *
     * <p>Разброс прицеливания раньше был 0.06 рад, но он не решал проблему
     * одновременных выстрелов, а только добавлял промахи: урон обеих стрел
     * оставался одинаковым, поэтому вторая всё равно отменялась кулдауном
     * урона в {@code LivingEntity.hurt()}. Вместо разброса используется
     * упреждение по скорости цели.
     */
    public static final double ARROW_LEAD_FACTOR = 1.0D;

    // ==================== Дистанции ====================

    /**
     * Ближе этой дистанции страж достаёт меч.
     *
     * <p>Раньше было 3.0 — на 3.1 страж ещё стрелял из арбалета в упор, а на 2.9
     * доставал меч. Зомби, топчущийся на границе, дёргал стража туда-сюда
     * (арбалет → меч → арбалет). Теперь меч достаётся заметно раньше.
     */
    public static final double MELEE_ENTER_DISTANCE = 4.0D;

    /**
     * Замах перед ударом (тики).
     *
     * <p>Без замаха удар прилетал в тот же тик, когда меч только появился в руке —
     * выглядело как мгновенный удар. 8 тиков — примерно треть секунды.
     */
    public static final int MELEE_WINDUP_TICKS = 5;

    /**
     * Сколько тиков рука возвращается после удара.
     *
     * <p>Раньше анимация была «вверх-вниз» целиком, и удар приходился на фазе 1.0 —
     * когда рука уже вернулась. Удар был не виден совсем. Теперь фаза удара
     * приходится на момент максимального размаха.
     */
    public static final int MELEE_SWING_RETURN_TICKS = 4;

    /**
     * Длительность анимации взмаха мечом (тики): замах + возврат руки.
     *
     * <p>Счётчик идёт в синхронизируемые данные, поэтому клиент рисует взмах
     * всегда — даже если пакет ванильной анимации не дошёл.
     */
    public static final int MELEE_SWING_ANIM_TICKS = MELEE_WINDUP_TICKS + MELEE_SWING_RETURN_TICKS;

    /** Фаза анимации, на которой приходится удар (0..1). */
    public static final float MELEE_SWING_STRIKE_PHASE = 0.6F;

    /**
     * Дальше этой дистанции страж возвращается к арбалету (гистерезис, чтобы не дёргался).
     *
     * <p>Широкий коридор 4..7: пока зомби в нём, страж остаётся в ближнем бою
     * и дерётся мечом, вместо того чтобы метаться между оружием.
     */
    public static final double MELEE_EXIT_DISTANCE = 7.0D;

    /** Максимальная дистанция, с которой страж ведёт огонь. */
    public static final double FIRE_MAX_DISTANCE = 16.0D;

    /** Ближе этой дистанции стрелять бессмысленно — враг уже вплотную. */
    public static final double FIRE_MIN_DISTANCE = 2.0D;

    /** Нижняя граница «рабочего» рубежа: страж старается держать дистанцию. */
    public static final double IDEAL_MIN_DISTANCE = 6.0D;

    /** Верхняя граница «рабочего» рубежа: дальше — сближается. */
    public static final double IDEAL_MAX_DISTANCE = 12.0D;

    /** Дальше этой дистанции цель считается потерянной. */
    public static final double TARGET_DROP_DISTANCE = 24.0D;

    /**
     * Радиус обнаружения врагов.
     *
     * <p>Раньше для этого использовалась {@link #IDEAL_MAX_DISTANCE} — но это
     * константа совсем о другом (дальний край рабочего рубежа в бою). Поднимать
     * её было нельзя: страж стал бы сближаться с врагом дальше
     * {@link #FIRE_MAX_DISTANCE}, откуда он не стреляет.
     *
     * <p>Должен оставаться меньше {@link #TARGET_DROP_DISTANCE}, иначе страж
     * находил бы цель дальше, чем она сбрасывается, и терял бы её каждый тик.
     */
    public static final double TARGET_DETECT_DISTANCE = 20.0D;

    /** Радиус поиска союзников при зове о помощи. */
    public static final double ALLY_SEARCH_RADIUS = 32.0D;

    /** Радиус, в котором союзник откликается на призыв. */
    public static final double RALLY_RADIUS = 24.0D;

    /** На какую дистанцию от врага страж отходит в панике, после чего ведёт огонь с места. */
    public static final double PANIC_RETREAT_DISTANCE = 10.0D;

    /** Радиус, в котором союзник слышит призыв и откликается. */
    public static final double RALLY_ARRIVE_DISTANCE = 3.0D;

    // ==================== Скорости ====================

    /** Скорость отхода в панике (вектор скорости, а не множитель скорости моба). */
    public static final double RETREAT_SPEED = 0.45D;

    /** Скорость сближения с врагом. */
    public static final double ADVANCE_SPEED = 0.28D;

    /**
     * Насколько далеко страж может отойти от своего рубежа.
     *
     * <p>Пятиться можно сколько угодно — но тогда страж «убегает» за карту.
     * Предел считается от якоря рубежа: страж пятится, удерживая дистанцию,
     * но не покидает окрестности своей позиции.
     */
    public static final double RETREAT_MAX_BACKSTEP = 12.0D;

    /** Скорость перемещения союзника к точке сбора (прямое движение, блоков за тик). */
    public static final double RALLY_SPEED = 0.30D;

    /** Скорость атаки в ближнем бою. */
    public static final double MELEE_SPEED = 0.65D;

    /** Скорость, с которой строится и проходится маршрут навигации. */
    public static final double NAV_SPEED = 1.0D;

    /** Через сколько тиков маршрут пересчитывается, даже если цель не двигалась. */
    public static final int NAV_RETARGET_INTERVAL = 10;

    /** Множитель скорости в воде: вязкость каждый тик гасит движение. */
    public static final double SWIM_SPEED_FACTOR = 0.9D;

    /** Минимальная вертикальная скорость в воде — держит страж на поверхности. */
    public static final double SWIM_BUOYANCY = 0.05D;

    // ==================== Тайминги (тики) ====================

    /** Сколько тиков нужно на полный заряд арбалета. */
    public static final int CROSSBOW_CHARGE_TICKS = 40;

    // ==================== Плавность движения ====================

    /**
     * Максимальная скорость доворота направления движения (градусов за тик).
     *
     * <p>Направление берётся из узла маршрута, а узел меняется при пересчёте
     * пути. Если писать скорость мгновенно, страж дёргался, и анимация шага
     * дёргалась вместе с ним. Теперь курс движения доворачивается к нужному
     * с этим пределом — как у ванильного {@code MoveControl.rotlerp} (90°/тик).
     *
     * <p>Меньше 60 страж не успевает развернуться: подошедший вплотную враг
     * отходит на него сам, и отступающий просто не выбирается из ближнего
     * круга. 90°/тик — это разворот на 180° за два тика, как у обычных мобов.
     */
    public static final float MOVE_TURN_SPEED_DEG = 45.0F;

    /**
     * Разгон и торможение на ходу (блоков за тик).
     *
     * <p>Применяется, когда страж уже движется: скорость подтягивается плавно,
     * и смена направления не читается как рывок. Старт с места — мгновенный
     * (см. {@code moveDirectly}): живой моб отталкивается сразу, и ждать
     * разгона нельзя — отходящий страж не успевает отойти от врага.
     */
    public static final double MOVE_ACCELERATION = 0.04D;

    /** Кулдаун зова о помощи (чтобы не спамить). */
    public static final int HELP_SCREAM_COOLDOWN = 200;

    /** Как часто страж в панике повторяет призыв. */
    public static final int SCREAM_INTERVAL = 100;

    /** Кулдаун поедания хлеба. */
    public static final int BREAD_COOLDOWN = 200;

    /** Сколько тиков союзник держит точку сбора. */
    public static final int RALLY_DURATION = 300;

    /** Как часто обновляется общий кэш стражей (раз в N тиков). */
    public static final int ALLY_SEARCH_INTERVAL = 40;

    /** Как часто пересканируется цель (раз в N тиков). */
    public static final int TARGET_SCAN_INTERVAL = 20;

    /** Кулдаун атаки в ближнем бою. */
    public static final int MELEE_ATTACK_COOLDOWN = 15;

    /** На каком расстоянии страж следит за игроком (взглядом, не целью). */
    public static final double LOOK_AT_PLAYER_DISTANCE = 8.0D;
}
